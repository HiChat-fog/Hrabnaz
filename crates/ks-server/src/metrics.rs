//! F3 可观测性 — Prometheus 指标导出
//!
//! 通过全局 Registry 暴露以下指标，供 `/metrics` 端点抓取：
//!
//! | 指标 | 类型 | Labels | 含义 |
//! |------|------|--------|------|
//! | `ks_events_total`              | Counter   | event_type | 累计事件总数（按事件类型） |
//! | `ks_alerts_total`              | Counter   | severity   | 累计告警总数（按严重级别） |
//! | `ks_map_entries`               | Gauge     | map_name   | eBPF map 当前条目数 |
//! | `ks_event_processing_seconds`  | Histogram | event_type | 事件处理延迟（秒，含默认桶） |
//! | `ks_tier_status`               | Gauge     | tier       | tier 激活状态（0=未激活 / 1=激活） |
//! | `ks_ringbuf_lost_total`        | Counter   | —          | ringbuf 丢失事件累计数 |
//!
//! 设计说明：
//! - 使用 `once_cell::sync::Lazy` + 全局 `Registry`，避免在 `ServerState` 中传递。
//! - 所有指标在模块加载时注册到全局 Registry，注册失败时 panic（开发期早暴露）。
//! - `render_metrics()` 用 `TextEncoder` 渲染为 Prometheus 文本格式，可直接作为 0.0.4 版本响应体。

use once_cell::sync::Lazy;
use prometheus::{
    Encoder, HistogramOpts, HistogramVec, IntCounter, IntCounterVec, IntGaugeVec, Opts, Registry,
    TextEncoder,
};

/// 全局 Prometheus Registry — 所有 ks-server 指标都注册到此处。
pub static REGISTRY: Lazy<Registry> = Lazy::new(|| {
    let r = Registry::new();

    // 注册各指标，失败时 panic（说明指标已注册 / 名称冲突，开发期必须修正）。
    r.register(Box::new(KS_EVENTS_TOTAL.clone()))
        .expect("register ks_events_total");
    r.register(Box::new(KS_ALERTS_TOTAL.clone()))
        .expect("register ks_alerts_total");
    r.register(Box::new(KS_MAP_ENTRIES.clone()))
        .expect("register ks_map_entries");
    r.register(Box::new(KS_EVENT_PROCESSING_SECONDS.clone()))
        .expect("register ks_event_processing_seconds");
    r.register(Box::new(KS_TIER_STATUS.clone()))
        .expect("register ks_tier_status");
    r.register(Box::new(KS_RINGBUF_LOST_TOTAL.clone()))
        .expect("register ks_ringbuf_lost_total");

    r
});

/// 累计事件总数（labels: event_type）。
/// event_type 取 eBPF 事件类型枚举的 u32 值（如 1=execve, 2=openat ...）。
pub static KS_EVENTS_TOTAL: Lazy<IntCounterVec> = Lazy::new(|| {
    IntCounterVec::new(
        Opts::new("ks_events_total", "Total events received by ks-server"),
        &["event_type"],
    )
    .expect("create ks_events_total")
});

/// 累计告警总数（labels: severity）。
/// severity 取 "low" / "medium" / "high" / "critical"。
pub static KS_ALERTS_TOTAL: Lazy<IntCounterVec> = Lazy::new(|| {
    IntCounterVec::new(
        Opts::new("ks_alerts_total", "Total alerts generated by ks-server"),
        &["severity"],
    )
    .expect("create ks_alerts_total")
});

/// eBPF map 当前条目数（labels: map_name）。
/// 由 stats 端点 / 后台轮询周期性 set，反映 5 个共享 map 的实时大小。
pub static KS_MAP_ENTRIES: Lazy<IntGaugeVec> = Lazy::new(|| {
    IntGaugeVec::new(
        Opts::new("ks_map_entries", "Current eBPF map entry count"),
        &["map_name"],
    )
    .expect("create ks_map_entries")
});

/// 事件处理延迟直方图（labels: event_type，单位：秒）。
/// 默认桶覆盖 5us ~ 10s 范围（prometheus crate 默认 11 个桶）。
pub static KS_EVENT_PROCESSING_SECONDS: Lazy<HistogramVec> = Lazy::new(|| {
    HistogramVec::new(
        HistogramOpts::new(
            "ks_event_processing_seconds",
            "Event processing latency in seconds",
        ),
        &["event_type"],
    )
    .expect("create ks_event_processing_seconds")
});

/// tier 激活状态（labels: tier，0=未激活 / 1=激活）。
/// tier 取 "modern" / "legacy" / "ancient"（对应项目 3 tier 检测体系）。
pub static KS_TIER_STATUS: Lazy<IntGaugeVec> = Lazy::new(|| {
    IntGaugeVec::new(
        Opts::new(
            "ks_tier_status",
            "Active tier status (0=inactive, 1=active)",
        ),
        &["tier"],
    )
    .expect("create ks_tier_status")
});

/// ringbuf 丢失事件累计数（无 label）。
/// 当 eBPF ringbuf 溢出（用户态消费不及）时累加。
pub static KS_RINGBUF_LOST_TOTAL: Lazy<IntCounter> = Lazy::new(|| {
    IntCounter::new("ks_ringbuf_lost_total", "Total ringbuf events lost")
        .expect("create ks_ringbuf_lost_total")
});

/// 渲染所有已注册指标为 Prometheus 文本格式 (0.0.4)。
///
/// 供 `/metrics` 端点直接返回；调用方应设置 Content-Type 为
/// `text/plain; version=0.0.4; charset=utf-8`。
pub fn render_metrics() -> String {
    // 触发 REGISTRY 初始化（Lazy::new 在首次解引用时执行注册）。
    let _ = &*REGISTRY;

    let mut buf = Vec::new();
    let encoder = TextEncoder::new();
    let metric_families = REGISTRY.gather();
    // 编码失败几乎不可能发生（仅 I/O 错误），失败时返回空字符串。
    if encoder.encode(&metric_families, &mut buf).is_err() {
        return String::new();
    }
    String::from_utf8(buf).unwrap_or_default()
}

/// 记录一次事件（按 event_type u32 累加 ks_events_total）。
/// 应在事件处理入口（EventSource / routes 事件循环）调用。
pub fn record_event(event_type: u32) {
    KS_EVENTS_TOTAL
        .with_label_values(&[&event_type.to_string()])
        .inc();
}

/// 记录一次告警（按 severity 累加 ks_alerts_total）。
/// severity 应取小写字符串："low" / "medium" / "high" / "critical"。
pub fn record_alert(severity: &str) {
    KS_ALERTS_TOTAL.with_label_values(&[severity]).inc();
}

/// 设置 tier 激活状态。active=true → 1, false → 0。
/// 在 start.rs 切换 tier 时调用。
pub fn set_tier_status(tier: &str, active: bool) {
    KS_TIER_STATUS
        .with_label_values(&[tier])
        .set(if active { 1 } else { 0 });
}

/// 记录一次 ringbuf 丢失事件。
pub fn record_ringbuf_lost() {
    KS_RINGBUF_LOST_TOTAL.inc();
}

/// 设置 eBPF map 当前条目数（后台轮询或 stats 端点调用）。
pub fn set_map_entries(map_name: &str, count: i64) {
    KS_MAP_ENTRIES.with_label_values(&[map_name]).set(count);
}
