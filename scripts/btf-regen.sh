#!/usr/bin/env bash
# Rebuild crates/hrabnaz-ebpf/btf/index.tsv and blobs/ from cached full BTF files.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
BTF=$ROOT/crates/hrabnaz-ebpf/btf
BLOBS=$BTF/blobs
INDEX=$BTF/index.tsv
CACHE=${HRABNAZ_BTF_CACHE:-$HOME/.cache/hrabnaz/btf-full}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

usage() {
    echo "usage: $0 --check | --all | --add <release>..." >&2
    exit 2
}

[ $# -ge 1 ] || usage
mode=$1
shift

find_objects() {
    local out
    while IFS= read -r out; do
        if [ -f "$out/hrabnaz_main_modern.o" ] && [ -f "$out/hrabnaz_main_legacy.o" ] &&
            [ -f "$out/hrabnaz_main_ancient.o" ]; then
            echo "$out"
            return 0
        fi
    done < <(find "$ROOT/target" -path '*/build/hrabnaz-engine-*/out/hrabnaz_main_modern.o' \
        -printf '%T@ %h\n' 2>/dev/null | sort -rn | cut -d' ' -f2-)
    echo "no build output with the three CO-RE objects; run cargo build -p hrabnaz-engine first" >&2
    return 1
}

check_index() {
    local fail=0 rel blob full actual
    local -A seen=()
    while IFS=$'\t' read -r rel blob full; do
        [[ $rel == \#* || -z ${rel:-} ]] && continue
        if [ -z "${blob:-}" ] || [ -z "${full:-}" ]; then
            echo "bad line: $rel" >&2
            fail=1
            continue
        fi
        if [ -n "${seen[$rel]:-}" ]; then
            echo "duplicate release: $rel" >&2
            fail=1
        fi
        seen[$rel]=1
        if [ ! -f "$BLOBS/$blob.min.btf" ]; then
            echo "missing blob: $blob ($rel)" >&2
            fail=1
            continue
        fi
        actual=$(sha256sum "$BLOBS/$blob.min.btf" | cut -d' ' -f1)
        if [[ $actual != "$blob"* ]]; then
            echo "blob hash mismatch: $blob ($rel)" >&2
            fail=1
        fi
        if [ -s "$CACHE/$rel.btf.tar.xz" ]; then
            local got
            got=$(tar -xOJf "$CACHE/$rel.btf.tar.xz" | sha256sum | cut -d' ' -f1)
            if [ "$got" != "$full" ]; then
                echo "cached source hash mismatch: $rel" >&2
                fail=1
            fi
        fi
    done <"$INDEX"

    while IFS= read -r f; do
        blob=$(basename "$f" .min.btf)
        if ! awk -F'\t' -v b="$blob" '!/^#/ && $2 == b' "$INDEX" | grep -q .; then
            echo "orphan blob: $(basename "$f")" >&2
        fi
    done < <(find "$BLOBS" -name '*.min.btf')

    [ $fail -eq 0 ] && echo "index ok: $(grep -vc '^#' "$INDEX") releases, $(find "$BLOBS" -name '*.min.btf' | wc -l) blobs"
    return $fail
}

trim_one() {
    local rel=$1 objdir=$2 tar min full
    tar="$CACHE/$rel.btf.tar.xz"
    if [ ! -s "$tar" ]; then
        "$ROOT/scripts/btf-fetch.sh" "$rel" >/dev/null || return 1
    fi
    tar -xOJf "$tar" >"$TMP/full.btf" 2>/dev/null || {
        echo "bad archive: $rel" >&2
        return 1
    }
    [ -s "$TMP/full.btf" ] || {
        echo "empty BTF: $rel" >&2
        return 1
    }
    full=$(sha256sum "$TMP/full.btf" | cut -d' ' -f1)
    if ! bpftool gen min_core_btf "$TMP/full.btf" "$TMP/min.btf" \
        "$objdir/hrabnaz_main_modern.o" "$objdir/hrabnaz_main_legacy.o" "$objdir/hrabnaz_main_ancient.o" \
        >/dev/null 2>&1; then
        echo "trim failed: $rel" >&2
        return 1
    fi
    min=$(sha256sum "$TMP/min.btf" | cut -d' ' -f1)
    min=${min:0:16}
    [ -f "$BLOBS/$min.min.btf" ] || cp "$TMP/min.btf" "$BLOBS/$min.min.btf"
    printf '%s\t%s\t%s\n' "$rel" "$min" "$full"
}

write_index() {
    {
        echo "# release	blob	full_btf_sha256"
        echo "# Generated by scripts/btf-regen.sh. blob = sha256(min BTF)[0:16]."
        sort -u "$1"
    } >"$INDEX"
}

build_index() {
    local objdir rel rc=0
    objdir=$(find_objects)
    command -v bpftool >/dev/null || {
        echo "bpftool not found" >&2
        exit 1
    }
    mkdir -p "$BLOBS"

    if [ "$mode" = "--all" ]; then
        mapfile -t releases < <(awk -F'\t' '!/^#/ && NF {print $1}' "$INDEX")
    else
        releases=("$@")
    fi

    for rel in "${releases[@]}"; do
        if ! trim_one "$rel" "$objdir" >>"$TMP/new.tsv"; then
            rc=$((rc + 1))
        fi
    done

    if [ "$mode" = "--all" ]; then
        cp "$TMP/new.tsv" "$TMP/final.tsv"
    else
        awk -F'\t' '!/^#/ && NF' "$INDEX" >"$TMP/old.tsv"
        cat "$TMP/old.tsv" "$TMP/new.tsv" 2>/dev/null >"$TMP/final.tsv"
    fi
    write_index "$TMP/final.tsv"

    echo "releases: $(grep -vc '^#' "$INDEX")  blobs: $(find "$BLOBS" -name '*.min.btf' | wc -l)  failed: $rc"
    [ $rc -eq 0 ]
}

case $mode in
--check) check_index ;;
--all | --add) build_index "$@" ;;
*) usage ;;
esac
